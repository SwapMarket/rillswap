import Ajv from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

for (const name of ["native-lightning", "native-lightning-manifest"]) {
  const schema = JSON.parse(readFileSync(new URL(`../../rill-docs/schemas/checkout/${name}.schema.json`, import.meta.url), "utf8"));
  const ajv = new Ajv({ strict: true, allErrors: true, code: { source: true, esm: true } });
  const generated = "// Generated by scripts/generate-validator.ts. Do not edit.\n" + standalone(ajv, ajv.compile(schema));
  const output = fileURLToPath(new URL(`../src/generated/${name}.js`, import.meta.url));
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== generated) throw new Error("Checkout validator is stale");
  } else {
    mkdirSync(fileURLToPath(new URL("../src/generated/", import.meta.url)), { recursive: true });
    writeFileSync(output, generated);
  }
}
